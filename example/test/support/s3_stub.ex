defmodule Example.Test.S3Stub do
  @moduledoc """
  A bucket that lives in ETS, so an export can be driven end to end offline.

  Everything else about the storage seam is offline already — a presigned URL is
  a signature computed locally, which is why `Example.Test.PresignHelpers` can
  assert on one without a network. `AshQuick.LiveView.ExportUtils` is the
  exception: it writes the generated file through `AshQuick.Storage.upload/3`,
  which is a real multipart `PUT`. Without something here the export can only be
  tested as far as the button.

  So this stands in for S3 at the HTTP layer rather than replacing the storage
  module: the CSV is really generated by `NimbleCSV`, the workbook really by
  `Exceed`, the key really built by `ExportUtils`, and the bytes that arrive are
  the bytes a reader would have downloaded. `body/1` hands them back. It
  also answers the `HEAD` and ranged `GET`s `AshQuick.Storage.S3.Proxy.Plug`
  reads an object back with.

  One row per part — keyed `{key, part_number}` rather than a parts list under
  the key — so an upload is a sequence of independent `insert`s. A list would
  have to be read, prepended to and written back, and two parts doing that at
  once lose one of themselves; `ExAws.S3.upload/4` is free to send parts
  concurrently, and does once a file is larger than one chunk.
  """

  @behaviour ExAws.Request.HttpClient

  @table __MODULE__
  @refusals Module.concat(__MODULE__, Refusals)

  @doc "Starts the tables. Called once from `test_helper.exs`."
  def start do
    :ets.new(@table, [:named_table, :public, :set, write_concurrency: true])
    :ets.new(@refusals, [:named_table, :public, :set])
    :ok
  end

  @doc """
  Refuses every upload whose key holds `prefix`, until `accept/1`.

  By prefix rather than for everything, so a test that makes an export fail
  fails only its own: the suite is async, and exports are keyed by the actor.
  The refusal is a `403`, which ExAws returns at once instead of retrying.

  With `hold: true` the refusing request first sends the calling process
  `{Example.Test.S3Stub, :held, pid}` and waits for `release/1` on that `pid`,
  so a test can act while the export is still running.
  """
  def refuse(prefix, opts \\ []) do
    holder = if Keyword.get(opts, :hold, false), do: self()
    :ets.insert(@refusals, {prefix, holder})
    :ok
  end

  @doc "Lets a request `refuse/2` is holding go on to its refusal."
  def release(pid) do
    send(pid, {__MODULE__, :release})
    :ok
  end

  @doc "Takes back `refuse/2`."
  def accept(prefix) do
    :ets.delete(@refusals, prefix)
    :ok
  end

  @doc """
  The bytes uploaded to `key`, or `nil` if nothing was.

  Parts are concatenated in order, which is what the object would be.
  """
  def body(key) do
    case parts(key) do
      [] -> nil
      parts -> parts |> Enum.sort_by(&elem(&1, 0)) |> Enum.map_join("", &elem(&1, 1))
    end
  end

  @doc """
  Every key written so far.

  Here rather than in the tests, so how a part is stored stays this module's
  business.
  """
  def keys do
    @table |> :ets.match({{:"$1", :_}, :_}) |> List.flatten() |> Enum.uniq()
  end

  @doc """
  Every `GET` made of `key` (`<bucket>/<key>`), oldest first, as the byte
  range it asked for, `{first, last}`, or `nil` for the whole object.
  """
  def reads(key) do
    @table
    |> :ets.match({{:read, key, :"$1"}, :"$2"})
    |> Enum.sort()
    |> Enum.map(fn [_order, range] -> range end)
  end

  @doc "Forgets everything, for a test that wants to assert nothing was written."
  def clear, do: :ets.delete_all_objects(@table)

  defp parts(key) do
    @table
    |> :ets.match({{key, :"$1"}, :"$2"})
    |> Enum.map(fn [number, body] -> {number, body} end)
  end

  @impl true
  def request(method, url, body, headers, _http_opts) do
    uri = URI.parse(url)
    query = URI.decode_query(uri.query || "")
    key = uri.path |> String.trim_leading("/") |> URI.decode()

    case refusal(key) do
      nil when method == :get -> read(key, range(headers))
      nil -> respond(method, key, query, body)
      {:refuse, holder} -> refuse_request(key, holder)
    end
  end

  # The key goes in the body, so a test can tell its own failure apart.
  defp refuse_request(key, holder) do
    if is_pid(holder) do
      send(holder, {__MODULE__, :held, self()})

      receive do
        {__MODULE__, :release} -> :ok
      after
        to_timeout(second: 5) -> :ok
      end
    end

    body = "<Error><Code>AccessDenied</Code><Key>#{key}</Key></Error>"
    {:ok, %{status_code: 403, headers: [], body: body}}
  end

  # By `String.contains?/2`, as the tests find an export: the path leads with
  # the bucket.
  defp refusal(path) do
    Enum.find_value(:ets.tab2list(@refusals), fn {prefix, holder} ->
      if String.contains?(path, prefix), do: {:refuse, holder}
    end)
  end

  # Initiate. The upload id is the key, since nothing here multiplexes.
  defp respond(:post, key, %{"uploads" => _}, _body) do
    xml("""
    <InitiateMultipartUploadResult>
      <UploadId>#{key}</UploadId>
    </InitiateMultipartUploadResult>
    """)
  end

  # Complete. The parts are already in the table.
  defp respond(:post, _key, %{"uploadId" => _}, _body) do
    xml("""
    <CompleteMultipartUploadResult>
      <ETag>"complete"</ETag>
    </CompleteMultipartUploadResult>
    """)
  end

  # One part of the object. `ExAws.S3.Upload` needs the `ETag` header back to
  # name it in the completion request.
  defp respond(:put, key, %{"partNumber" => number}, body) do
    :ets.insert(@table, {{key, String.to_integer(number)}, body})

    {:ok, %{status_code: 200, headers: [{"ETag", ~s("#{number}")}], body: ""}}
  end

  # A single-shot `PUT`, for anything that does not go through the multipart
  # path.
  defp respond(:put, key, _query, body) do
    :ets.match_delete(@table, {{key, :_}, :_})
    :ets.insert(@table, {{key, 1}, body})
    {:ok, %{status_code: 200, headers: [{"ETag", ~s("1")}], body: ""}}
  end

  # What `AshQuick.Storage.S3.Proxy.Plug` reads an object with: a `HEAD` for
  # its size, then ranged `GET`s (`read/2`). The path leads with the bucket, so the key
  # here is `<bucket>/<key>`.
  defp respond(:head, key, _query, _body) do
    case body(key) do
      nil ->
        {:ok, %{status_code: 404, headers: [], body: ""}}

      bytes ->
        {:ok, %{status_code: 200, headers: [{"Content-Length", "#{byte_size(bytes)}"}], body: ""}}
    end
  end

  defp respond(_method, _key, _query, _body) do
    {:ok, %{status_code: 200, headers: [], body: ""}}
  end

  defp read(key, range) do
    :ets.insert(@table, {{:read, key, System.unique_integer([:monotonic])}, range})

    case {body(key), range} do
      {nil, _range} ->
        {:ok, %{status_code: 404, headers: [], body: ""}}

      {bytes, {first, last}} ->
        last = min(last, byte_size(bytes) - 1)
        {:ok, %{status_code: 206, headers: [], body: binary_part(bytes, first, last - first + 1)}}

      {bytes, nil} ->
        {:ok, %{status_code: 200, headers: [], body: bytes}}
    end
  end

  defp range(headers) do
    Enum.find_value(headers, fn {name, value} ->
      with "range" <- String.downcase(name),
           "bytes=" <> spec <- value,
           [first, last] <- String.split(spec, "-") do
        {String.to_integer(first), String.to_integer(last)}
      else
        _other -> nil
      end
    end)
  end

  defp xml(body), do: {:ok, %{status_code: 200, headers: [], body: body}}
end
